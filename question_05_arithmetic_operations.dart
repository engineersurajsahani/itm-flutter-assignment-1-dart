// Question 5: Arithmetic operations
// Perform +, -, *, /, ~/ (integer division), and % on two integers.

void main() {
  int a = 20;
  int b = 6;

  print('a = $a');
  print('b = $b');
  print('');

  print('Addition: ${a + b}');
  print('Subtraction: ${a - b}');
  print('Multiplication: ${a * b}');
  print('Division: ${a / b}');
  print('Integer division: ${a ~/ b}');
  print('Remainder: ${a % b}');
}
