//Perform +, -, *, /, ~/ (integer division), and % on two integers. Print each result.
//Operators

void main() {
  int a = 40;
  int b = 60;

  print("Addition = ${a + b}");
  print("Subtraction = ${a - b}");
  print("Multiplication = ${a * b}");
  print("Division = ${a / b}");
  print("Integer Division = ${a ~/ b}");
  print("Remainder = ${a % b}");
}