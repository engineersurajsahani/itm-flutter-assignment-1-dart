/*
 * Question 8: Celsius to Fahrenheit
 * Description: Take temperature in Celsius (double), convert to Fahrenheit using formula (C * 9/5) + 32. Print result.
 * Category: Operators / Data type
 */

void main() {
  double celsius = 37.5;
  double fahrenheit = (celsius * 9 / 5) + 32;

  print("Temperature in Celsius: $celsius°C");
  print("Temperature in Fahrenheit: $fahrenheit°F");
}
